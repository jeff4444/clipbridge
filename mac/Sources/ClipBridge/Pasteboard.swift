import AppKit
import UniformTypeIdentifiers

extension NSPasteboard.PasteboardType {
    // http://nspasteboard.org conventions used by password managers and clipboard tools.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// Marks pasteboard contents that ClipBridge itself put there, so they are not sent back.
    static let clipBridge = NSPasteboard.PasteboardType("dev.clipbridge.remote")
    static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    static let gif = NSPasteboard.PasteboardType("com.compuserve.gif")
    static let heic = NSPasteboard.PasteboardType("public.heic")
    static let webp = NSPasteboard.PasteboardType("org.webmproject.webp")
}

/// What the pasteboard holds, as far as can be told without touching the file system.
enum PasteboardSnapshot {
    case items([ClipItem], sensitive: Bool)
    /// File URLs (a Finder copy). Turning these into clip items needs the file system.
    case files([URL], sensitive: Bool)
}

enum FileItemsResult {
    case items([ClipItem])
    case denied              // macOS privacy protection refused access
    case skipped(String)     // nothing syncable: folders only, too large, …
}

enum PasteboardReader {
    /// Main thread. What should be synced for the current pasteboard contents, or nil if nothing
    /// should. Never touches the file system: reading even the size of a file in Documents,
    /// Desktop or Downloads can block on a macOS permission prompt.
    static func snapshot(maxBytes: Int64) -> PasteboardSnapshot? {
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        if types.contains(.clipBridge) || types.contains(.transient) || types.contains(.autoGenerated) { return nil }
        let sensitive = types.contains(.concealed)

        // 1. Files copied in Finder (or any app that puts file URLs on the pasteboard).
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(Array(urls.prefix(20)), sensitive: sensitive)
        }

        let text = pb.string(forType: .string)

        // 2. Images (screenshots, "Copy Image" in a browser, image editors).
        if prefersImage(text: text, types: types), let image = imageData(pb, types: types) {
            if Int64(image.data.count) > maxBytes { return nil }
            let item = ClipItem(kind: "file", mime: image.mime, name: image.name, size: Int64(image.data.count), body: .data(image.data))
            return .items([item], sensitive: sensitive)
        }

        // 3. Text, with HTML alongside when the source app provided it.
        guard let text, !text.isEmpty else { return nil }
        let utf8 = Data(text.utf8)
        if Int64(utf8.count) > maxBytes { return nil }
        var items = [ClipItem(kind: "text", mime: "text/plain", name: "", size: Int64(utf8.count), body: .data(utf8))]
        if let html = pb.string(forType: .html), !html.isEmpty, html.utf8.count < 2_000_000 {
            let h = Data(html.utf8)
            items.append(ClipItem(kind: "html", mime: "text/html", name: "", size: Int64(h.count), body: .data(h)))
        }
        return .items(items, sensitive: sensitive)
    }

    /// Background queue only. Looks at the copied files. The first time a protected folder is
    /// involved this blocks until the user answers the macOS permission prompt.
    static func fileItems(_ urls: [URL], maxBytes: Int64) -> FileItemsResult {
        var items: [ClipItem] = []
        var total: Int64 = 0
        var denied = false
        for url in urls {
            do {
                let values = try url.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
                if values.isDirectory == true { continue }
                let size = Int64(values.fileSize ?? 0)
                guard size > 0 else { continue }
                // Open it once here. If macOS needs to ask the user about this folder, the prompt
                // is waited out on this queue; by the time the network code opens the file to send
                // it, the answer is already known and that open cannot stall syncing.
                let probe = try FileHandle(forReadingFrom: url)
                try? probe.close()
                total += size
                let mime = UTType(filenameExtension: url.pathExtension)?.preferredMIMEType ?? "application/octet-stream"
                items.append(ClipItem(kind: "file", mime: mime, name: url.lastPathComponent, size: size, body: .file(url)))
            } catch let error as NSError {
                let cocoaDenied = error.domain == NSCocoaErrorDomain && error.code == NSFileReadNoPermissionError
                let posixDenied = error.domain == NSPOSIXErrorDomain && (error.code == Int(EPERM) || error.code == Int(EACCES))
                if cocoaDenied || posixDenied { denied = true }
            }
        }
        if items.isEmpty { return denied ? .denied : .skipped("copied item is a folder or empty; not synced") }
        if total > maxBytes { return .skipped("copied files are too large to sync (\(total) bytes)") }
        return .items(items)
    }

    /// Spreadsheet cells, notes and the like put a picture of the text on the pasteboard too.
    /// Only treat a copy as an image when there is no real text beside it.
    private static func prefersImage(text: String?, types: [NSPasteboard.PasteboardType]) -> Bool {
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .jpeg, .gif, .heic, .webp]
        guard types.contains(where: { imageTypes.contains($0) }) else { return false }
        guard let text, !text.isEmpty else { return true }
        if types.contains(.URL) { return true } // Safari "Copy Image": image plus its address
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.contains(" ") && !trimmed.contains("\n") && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
    }

    private static func imageData(_ pb: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> (data: Data, mime: String, name: String)? {
        let passthrough: [(NSPasteboard.PasteboardType, String, String)] = [
            (.png, "image/png", "png"), (.jpeg, "image/jpeg", "jpg"), (.gif, "image/gif", "gif"),
            (.webp, "image/webp", "webp"),
        ]
        for (type, mime, ext) in passthrough where types.contains(type) {
            if let d = pb.data(forType: type), !d.isEmpty { return (d, mime, "image.\(ext)") }
        }
        // TIFF / HEIC: convert to PNG so every Android app can open it.
        for type in [NSPasteboard.PasteboardType.tiff, .heic] where types.contains(type) {
            if let d = pb.data(forType: type), let rep = NSBitmapImageRep(data: d),
               let png = rep.representation(using: .png, properties: [:]) {
                return (png, "image/png", "image.png")
            }
        }
        return nil
    }
}

/// Supplies TIFF/PNG renditions of a received image only if an app actually asks for them.
private final class LazyImageProvider: NSObject, NSPasteboardItemDataProvider {
    private let original: Data
    init(_ original: Data) { self.original = original }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard let rep = NSBitmapImageRep(data: original) else { return }
        if type == .tiff, let d = rep.tiffRepresentation {
            item.setData(d, forType: .tiff)
        } else if type == .png, let d = rep.representation(using: .png, properties: [:]) {
            item.setData(d, forType: .png)
        }
    }
}

enum PasteboardWriter {
    private static var provider: LazyImageProvider? // must outlive the pasteboard contents

    /// Puts a clip from the phone on the Mac pasteboard. Returns the resulting change count.
    @discardableResult
    static func write(_ clip: Clip) -> Int? {
        let pb = NSPasteboard.general
        guard let first = clip.items.first else { return nil }

        if first.kind == "text", case .data(let d) = first.body, let text = String(data: d, encoding: .utf8) {
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            if let h = clip.items.first(where: { $0.kind == "html" }), case .data(let hd) = h.body,
               let html = String(data: hd, encoding: .utf8) {
                item.setString(html, forType: .html)
            }
            mark(item, clip)
            pb.clearContents()
            pb.writeObjects([item])
            return pb.changeCount
        }

        let files = clip.items.compactMap { item -> (ClipItem, URL)? in
            if item.kind == "file", case .file(let url) = item.body { return (item, url) }
            return nil
        }
        guard !files.isEmpty else { return nil }

        // A single still image is pasted as image data, like a screenshot would be.
        if files.count == 1, let (meta, url) = files.first, meta.mime.hasPrefix("image/"), meta.mime != "image/gif",
           let data = try? Data(contentsOf: url), NSBitmapImageRep(data: data) != nil {
            let item = NSPasteboardItem()
            let lazy = LazyImageProvider(data)
            provider = lazy
            switch meta.mime {
            case "image/png":
                item.setData(data, forType: .png)
                item.setDataProvider(lazy, forTypes: [.tiff])
            case "image/jpeg":
                item.setData(data, forType: .jpeg)
                item.setDataProvider(lazy, forTypes: [.png, .tiff])
            default:
                // WebP/HEIC/…: most Mac apps cannot paste these directly, so convert up front.
                guard let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { return nil }
                item.setData(png, forType: .png)
                item.setDataProvider(lazy, forTypes: [.tiff])
            }
            mark(item, clip)
            pb.clearContents()
            pb.writeObjects([item])
            return pb.changeCount
        }

        // Anything else is pasted as files, exactly as if copied in Finder. The URLs are written
        // eagerly (not as lazily-provided NSURL objects) so they survive this process exiting.
        var items: [NSPasteboardItem] = []
        for (i, file) in files.enumerated() {
            let item = NSPasteboardItem()
            item.setString(file.1.absoluteString, forType: .fileURL)
            if i == 0 { mark(item, clip) }
            items.append(item)
        }
        pb.clearContents()
        pb.writeObjects(items)
        return pb.changeCount
    }

    private static func mark(_ item: NSPasteboardItem, _ clip: Clip) {
        item.setData(Data(), forType: .clipBridge)
        if clip.sensitive { item.setData(Data(), forType: .concealed) } // keeps it out of clipboard-history apps
    }
}

/// macOS has no pasteboard change notification; polling the change count is the standard approach
/// and costs next to nothing.
final class PasteboardWatcher {
    private let onChange: () -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var pending = false

    init(onChange: @escaping () -> Void) {
        self.onChange = onChange
    }

    func start() {
        let t = Timer(timeInterval: 0.15, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.03
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after writing to the pasteboard ourselves.
    func ignoreCurrent() {
        lastCount = NSPasteboard.general.changeCount
    }

    private func tick() {
        let count = NSPasteboard.general.changeCount
        guard count != lastCount, !pending else { return }
        pending = true
        // Some apps fill the pasteboard in several steps; give them a moment to finish.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { [weak self] in
            guard let self else { return }
            self.pending = false
            self.lastCount = NSPasteboard.general.changeCount
            self.onChange()
        }
    }
}
